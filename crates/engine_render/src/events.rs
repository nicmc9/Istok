//! Сообщения рендера главному потоку (Б-08): отказы, о которых главный поток сам не узнает.
//!
//! Обычный обмен идёт иначе: статистика — атомарными счётчиками, ответы на запросы
//! (surface отпущен, скриншот) — через `oneshot`. Сюда попадает только то, что рендер
//! сообщает сам, без запроса.

use engine_core::CVar;
use engine_ecs::prelude::*;

/// Отказ рендера. Приходит сообщением ECS в стадии `First`.
#[derive(Message, Debug, Clone, PartialEq, Eq)]
pub enum RenderEvent {
    /// Устройство GPU потеряно (сброс драйвера, ОС отобрала GPU). Рендер создаёт новое,
    /// меши, текстуры, материалы, атлас текста и интерфейс движок отправляет заново сам.
    DeviceLost(String),
    /// GPU не создался: нет адаптера или драйвер отказал. Кадров не будет.
    GpuFailed(String),
    /// Поток рендера упал. Приложение завершается.
    Crashed(String),
}

/// Отладка: потерять устройство GPU. Главный поток сбрасывает флаг и отправляет рендеру
/// команду, рендер вызывает `device.destroy()` и дальше идёт обычным путём потери.
pub static RENDER_DEBUG_LOSE_DEVICE: CVar<bool> = CVar::new(
    "render.debug_lose_device",
    false,
    "Отладка: потерять устройство GPU, рендер пересоздаст его и ресурсы",
);
